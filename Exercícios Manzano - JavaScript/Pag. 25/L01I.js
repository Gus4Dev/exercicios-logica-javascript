// Programa: Quadrado da Diferença entre Dois Números

alert("Programa de Cálculo do Quadrado da Diferença entre Dois Números");

var a = parseInt(prompt("Digite o valor de A: "));
var b = parseInt(prompt("Digite o valor de B: "));
var resultado = (a - b) * (a - b);

alert("O quadrado da diferença é: " + resultado);