// Programa: Soma dos Quadrados de Três Valores

alert("Programa de Cálculo da Soma dos Quadrados de Três Valores");

var a = parseFloat(prompt("Digite o valor de A: "));
var b = parseFloat(prompt("Digite o valor de B: "));
var c = parseFloat(prompt("Digite o valor de C: "));
var resultado = (a * a) + (b * b) + (c * c);

alert("A soma dos quadrados é: " + resultado);